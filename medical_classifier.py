import sys
import re
import time
from pathlib import Path
import pandas as pd
import numpy as np

from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.naive_bayes import MultinomialNB
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import StratifiedKFold, cross_val_score
from sklearn.metrics import accuracy_score, classification_report
import joblib

# -----------------------------------------------------------------------------
# Configuration and Paths
# -----------------------------------------------------------------------------
BASE_DIR = Path(__file__).resolve().parent
DATA_DIR = BASE_DIR / "data"
MODELS_DIR = BASE_DIR / "models"
MODELS_DIR.mkdir(exist_ok=True)

TRAIN_PATH = DATA_DIR / "medical_tc_train.csv"
TEST_PATH = DATA_DIR / "medical_tc_test.csv"
LABELS_PATH = DATA_DIR / "medical_tc_labels.csv"

BEST_MODEL_PATH = MODELS_DIR / "selected_best_model.joblib"
VECTORIZER_PATH = MODELS_DIR / "selected_vectorizer.joblib"

DISCLAIMER_TEXT = """
*******************************************************************************
                            IMPORTANT NOTICE / DISCLAIMER
 This console application is an academic NLP research tool designed for
 educational and study purposes only.
 Predictions generated by this system are based on statistical text patterns
 in scientific research abstracts. This tool does NOT provide medical diagnoses,
 clinical recommendations, or medical advice.
*******************************************************************************
"""

# -----------------------------------------------------------------------------
# 1. Text Preprocessing Function
# -----------------------------------------------------------------------------
def clean_medical_text(text: str) -> str:
    """
    Cleans raw medical text while preserving domain-critical vocabulary:
    - Lowercases text for uniform representation.
    - Strips URLs.
    - Replaces brackets, quotes, and punctuation with spaces.
    - Preserves intra-word hyphens (e.g., 'anti-inflammatory', 'neuron-specific').
    - Preserves decimal numbers (e.g., '1.5') and alphanumeric terms (e.g., 'cd4', 'mac16').
    - Normalizes extra whitespace.
    """
    if not isinstance(text, str):
        return ""

    cleaned = text.lower()
    cleaned = re.sub(r"https?://\S+|www\.\S+", " ", cleaned)
    cleaned = re.sub(r'[\(\)\[\]\{\}\"\'\\\/<>,;:!+*?=~_]', " ", cleaned)
    cleaned = re.sub(r"(?<!\w)-|-(?!\w)", " ", cleaned)
    cleaned = re.sub(r"(?<!\d)\.|\.(?!\d)", " ", cleaned)
    cleaned = re.sub(r"\s+", " ", cleaned).strip()
    return cleaned


# -----------------------------------------------------------------------------
# 2. Dataset Loading and Verification
# -----------------------------------------------------------------------------
def verify_and_load_datasets():
    """Verifies that dataset files exist and loads them into DataFrames."""
    missing_files = []
    for p in [TRAIN_PATH, TEST_PATH, LABELS_PATH]:
        if not p.exists():
            missing_files.append(p.name)

    if missing_files:
        print("\n[ERROR] Required dataset files are missing inside the 'data/' folder:")
        for mf in missing_files:
            print(f"  - data/{mf}")
        print("\nPlease run 'python inspect_dataset.py' or download the dataset files first.")
        sys.exit(1)

    print("Loading verified dataset files...")
    train_df = pd.read_csv(TRAIN_PATH)
    test_df = pd.read_csv(TEST_PATH)
    labels_df = pd.read_csv(LABELS_PATH)

    label_map = dict(zip(labels_df["condition_label"], labels_df["condition_name"]))
    print(f"Loaded {len(train_df):,} training samples and {len(test_df):,} test samples.")
    print("Categories recognized:")
    for cid, cname in sorted(label_map.items()):
        print(f"  [{cid}] {cname}")

    return train_df, test_df, label_map


# -----------------------------------------------------------------------------
# 3. Model Training, Validation Selection & Test Evaluation
# -----------------------------------------------------------------------------
def train_and_select_model(train_df, test_df, label_map):
    """
    Performs scientifically sound model selection:
    1. Preprocesses train and test text.
    2. Fits TF-IDF vectorizer strictly on training data.
    3. Runs 5-Fold Cross-Validation on the training set to choose the best model.
    4. Evaluates the chosen model on the held-out test set.
    5. Saves the selected model and vectorizer to disk for fast subsequent runs.
    """
    print("\n" + "=" * 75)
    print(" MODEL TRAINING & VALIDATION SELECTION")
    print("=" * 75)

    print("\n[Step 1/4] Preprocessing raw text...")
    X_train_raw = train_df["medical_abstract"].apply(clean_medical_text)
    X_test_raw = test_df["medical_abstract"].apply(clean_medical_text)
    y_train = train_df["condition_label"]
    y_test = test_df["condition_label"]

    print("\n[Step 2/4] Extracting TF-IDF features (Vocabulary limit: 10,000 terms)...")
    vectorizer = TfidfVectorizer(
        max_features=10000,
        ngram_range=(1, 2),
        stop_words="english",
        sublinear_tf=True
    )
    X_train_tfidf = vectorizer.fit_transform(X_train_raw)
    X_test_tfidf = vectorizer.transform(X_test_raw)
    print(f"Fitted TF-IDF vocabulary on training data: {X_train_tfidf.shape[1]:,} features.")

    # Candidate Models
    candidates = {
        "Multinomial Naive Bayes": MultinomialNB(alpha=0.1),
        "Logistic Regression": LogisticRegression(max_iter=1000, random_state=42, C=1.0)
    }

    # 5-Fold Cross Validation on Training Data
    print("\n[Step 3/4] Performing 5-Fold Stratified Cross-Validation on training data...")
    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
    val_scores = {}

    for name, model in candidates.items():
        print(f"  Evaluating {name} with 5-fold CV...")
        scores = cross_val_score(model, X_train_tfidf, y_train, cv=cv, scoring="accuracy", n_jobs=-1)
        mean_score = float(np.mean(scores))
        std_score = float(np.std(scores))
        val_scores[name] = mean_score
        print(f"  -> {name} Mean Validation Accuracy: {mean_score * 100:.2f}% (+/- {std_score * 100:.2f}%)")

    # Select best model based on validation performance
    best_model_name = max(val_scores, key=val_scores.get)
    print(f"\n>> WINNING MODEL SELECTED: {best_model_name} (Validation Accuracy: {val_scores[best_model_name] * 100:.2f}%)")

    # Final Fit on full training data
    print(f"\n[Step 4/4] Fitting winning model ({best_model_name}) on full training data...")
    selected_model = candidates[best_model_name]
    t0 = time.time()
    selected_model.fit(X_train_tfidf, y_train)
    fit_time = time.time() - t0
    print(f"Model fit complete in {fit_time:.3f} seconds.")

    # Evaluate on held-out test data
    print("\nEvaluating winning model on the held-out test set (2,888 abstracts)...")
    test_preds = selected_model.predict(X_test_tfidf)
    test_accuracy = accuracy_score(y_test, test_preds)
    print(f">> Final Test Accuracy: {test_accuracy * 100:.2f}%")

    target_names = [label_map[i] for i in sorted(label_map.keys())]
    print("\nTest Set Classification Report:")
    print(classification_report(y_test, test_preds, target_names=target_names, digits=4))

    # Save to disk
    joblib.dump(selected_model, BEST_MODEL_PATH)
    joblib.dump(vectorizer, VECTORIZER_PATH)
    print(f"Saved selected model and vectorizer to '{MODELS_DIR}'.")

    return selected_model, vectorizer, best_model_name, test_accuracy


# -----------------------------------------------------------------------------
# 4. Single Abstract Prediction Function
# -----------------------------------------------------------------------------
def predict_abstract(abstract_text: str, model, vectorizer, label_map: dict):
    """
    Cleans, vectorizes, and predicts category and probabilities for a single abstract.
    """
    # 1. Clean input text
    cleaned = clean_medical_text(abstract_text)
    if not cleaned or len(cleaned.split()) < 3:
        return None, "Input is too short to extract meaningful medical features. Please enter a full abstract."

    # 2. Transform using fitted vectorizer
    vectorized = vectorizer.transform([cleaned])

    # 3. Predict class
    pred_class_id = int(model.predict(vectorized)[0])
    pred_category_name = label_map.get(pred_class_id, "Unknown Category")

    # 4. Predict probabilities if available
    probabilities = {}
    if hasattr(model, "predict_proba"):
        probs = model.predict_proba(vectorized)[0]
        # Match probabilities to classes in model.classes_
        for class_id, prob in zip(model.classes_, probs):
            cat_name = label_map.get(int(class_id), f"Category {class_id}")
            probabilities[cat_name] = float(prob)

    return {
        "class_id": pred_class_id,
        "category_name": pred_category_name,
        "probabilities": probabilities,
        "cleaned_length": len(cleaned.split()),
    }, None


# -----------------------------------------------------------------------------
# 5. Interactive Console Interface
# -----------------------------------------------------------------------------
def run_interactive_console(model, vectorizer, label_map: dict, model_name: str, test_acc: float):
    """Provides a user-friendly console interaction loop."""
    print("\n" + "=" * 75)
    print(" MEDICAL TEXT CLASSIFICATION - INTERACTIVE CONSOLE")
    print("=" * 75)
    print(DISCLAIMER_TEXT)
    print(f"Active Classifier : {model_name} (Held-out Test Accuracy: {test_acc * 100:.2f}%)")
    print("Instructions      : Paste or type a medical research abstract.")
    print("                    Type 'exit' or 'quit' to close the program.")
    print("-" * 75)

    prediction_count = 0

    while True:
        try:
            print("\nEnter medical research abstract:")
            user_input = input(">> ").strip()

            if not user_input:
                print("[Warning] Empty input received. Please provide a medical abstract text.")
                continue

            if user_input.lower() in ["exit", "quit", "q"]:
                print(f"\nExiting application. Total abstracts classified in this session: {prediction_count}")
                print("Thank you for using the Medical Text Classification system!")
                break

            result, error_msg = predict_abstract(user_input, model, vectorizer, label_map)

            if error_msg:
                print(f"[Warning] {error_msg}")
                continue

            prediction_count += 1
            print("\n" + "-" * 55)
            print(f" PREDICTION RESULT #{prediction_count}")
            print("-" * 55)
            print(f" Predicted Category : [{result['class_id']}] {result['category_name'].upper()}")
            print("-" * 55)

            if result["probabilities"]:
                print(" Category Confidence Probabilities:")
                # Sort probabilities descending
                sorted_probs = sorted(result["probabilities"].items(), key=lambda x: x[1], reverse=True)
                for cat, prob in sorted_probs:
                    bar_length = int(prob * 30)
                    bar = "#" * bar_length + "-" * (30 - bar_length)
                    print(f"   - {cat:<32} : {prob * 100:>5.1f}% [{bar}]")

            print("-" * 55)

        except (KeyboardInterrupt, EOFError):
            print("\nSession interrupted. Exiting gracefully. Goodbye!")
            break


# -----------------------------------------------------------------------------
# Main Entry Point
# -----------------------------------------------------------------------------
def main():
    print(DISCLAIMER_TEXT)

    # 1. Verify and load datasets
    train_df, test_df, label_map = verify_and_load_datasets()

    # 2. Check if trained model is already cached, or train from scratch
    if BEST_MODEL_PATH.exists() and VECTORIZER_PATH.exists():
        print(f"\nFound existing trained model at: {BEST_MODEL_PATH.name}")
        print("Would you like to (1) Use cached model, or (2) Re-train from scratch with cross-validation?")
        # Non-interactive fallback: If standard input is automated or piped, use cached or re-train
        choice = "1"
        if sys.stdin.isatty():
            user_choice = input("Enter choice (1/2, default 1): ").strip()
            if user_choice in ["1", "2"]:
                choice = user_choice

        if choice == "1":
            print("Loading cached model and vectorizer...")
            model = joblib.load(BEST_MODEL_PATH)
            vectorizer = joblib.load(VECTORIZER_PATH)
            model_name = type(model).__name__
            # Quick evaluation on test data to display genuine accuracy
            X_test_raw = test_df["medical_abstract"].apply(clean_medical_text)
            X_test_tfidf = vectorizer.transform(X_test_raw)
            test_acc = accuracy_score(test_df["condition_label"], model.predict(X_test_tfidf))
        else:
            model, vectorizer, model_name, test_acc = train_and_select_model(train_df, test_df, label_map)
    else:
        model, vectorizer, model_name, test_acc = train_and_select_model(train_df, test_df, label_map)

    # 3. Launch interactive prediction loop
    run_interactive_console(model, vectorizer, label_map, model_name, test_acc)


if __name__ == "__main__":
    main()
